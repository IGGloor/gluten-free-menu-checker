// The CTA is enabled only with at least one preference AND a menu link or PDF.
function updateCta() {
  const ready =
    selectedPreferences().length > 0 && (urlInput.value.trim() !== "" || fileInput.files.length > 0);
  submitBtn.disabled = !ready;
  ctaHelper.hidden = ready;
}

// — Submit to n8n —

form.addEventListener("submit", async (event) => {
  event.preventDefault();
  hideError();

  const selected = selectedPreferences();
  const preferences = selected.map((b) => b.dataset.value);
  const shortPreferences = selected.map((b) => b.dataset.short);
  const menuUrl = urlInput.value.trim();
  const menuFile = fileInput.files[0];

  if (preferences.length === 0) {
    return showError("Please select at least one dietary preference.");
  }
  if (!menuUrl && !menuFile) {
    return showError("Please add a link to the restaurant's menu.");
  }
  if (menuUrl && !urlInput.checkValidity()) {
    return showError("That link doesn't look right. It should start with http:// or https://");
  }

  const formData = new FormData();
  formData.append("preferences", preferences.join(", "));
  formData.append("menuUrl", menuUrl);
  if (menuFile) {
    formData.append("menu", menuFile, menuFile.name);
  }

  setLoading(true);

  try {
    const response = await fetch(N8N_WEBHOOK_URL, { method: "POST", body: formData });
    const body = await response.text();

    if (!response.ok) {
      throw new Error(`n8n responded with ${response.status}: ${body || response.statusText}`);
    }

    const reply = parseResponse(body);
    lastResult = {
      message: reply.message,
      dishes: reply.dishes || extractDishes(reply.message),
      restaurant: reply.restaurant || guessRestaurantName(menuUrl, menuFile),
      location: reply.location || null,
      preferences,
      shortPreferences,
      menuUrl,
    };
    await finishLoading();
    showResult(lastResult);
  } catch (error) {
    lastResult = null;
    setLoading(false);
    const hint =
      error instanceof TypeError
        ? " Could not reach n8n. Check that it is running, the webhook URL is correct, and CORS is allowed."
        : "";
    showError(error.message + hint);
    urlInput.focus();
  }
});

// n8n can reply with plain text or JSON. The AI Agent node puts its answer in "output".
// Optional fields for the PDF: restaurantName (or restaurant / name) and location (or address).
// Optional "dishes": [{ name, verdict: "clear" | "ask" | "avoid", note }] skips the text parsing.
function parseResponse(body) {
  let data;
  try {
    data = JSON.parse(body);
  } catch {
    return { message: body };
  }
  if (Array.isArray(data)) data = data[0];
  if (typeof data === "string") return { message: data };

  return {
    message:
      data.output ?? data.text ?? data.response ?? data.message ?? JSON.stringify(data, null, 2),
    restaurant: data.restaurantName ?? data.restaurant ?? data.name,
    location: data.location ?? data.restaurantLocation ?? data.address,
    dishes: normaliseDishes(data.dishes),
  };
}

function normaliseDishes(dishes) {
  if (!Array.isArray(dishes) || dishes.length === 0) return null;
  const list = dishes
    .map((d) => ({
      name: String(d.name ?? d.dish ?? "").trim(),
      note: String(d.note ?? d.notes ?? d.reason ?? "").trim(),
      verdict: classifySection(String(d.verdict ?? d.status ?? "")) || "ask",
    }))
    .filter((d) => d.name);
  return list.length ? sortDishes(list) : null;
}

// Fallback when n8n doesn't send a name: "https://www.ramenhead.co.za/menu" -> "Ramenhead"
function guessRestaurantName(menuUrl, menuFile) {
  let name = "";
  if (menuUrl) {
    try {
      name = new URL(menuUrl).hostname.replace(/^www\./, "").split(".")[0];
    } catch {}
  }
  if (!name && menuFile) name = menuFile.name.replace(/\.pdf$/i, "");
  name = name.replace(/[-_]+/g, " ").trim();
  return name ? name.replace(/\b\w/g, (c) => c.toUpperCase()) : "Restaurant";
}

// — Turning the AI's text reply into rated dishes —
// The reply is grouped into sections (e.g. "*🟢 Naturally Gluten-Free*", "## Ask for changes",
// "🔴 Avoid"). Each bullet under a section becomes a dish with that section's verdict.

const MARKER = /^(🟢|🟡|🟠|🔴|✅|❌|⛔|⚠️?)\s*/u;

function extractDishes(text) {
  const dishes = [];
  let verdict = null;

  for (const raw of String(text).split("\n")) {
    const line = raw.trim();
    if (!line) continue;

    const bullet = line.match(/^(?:[-*•]|\d+[.)])\s+(.*)/);
    if (bullet) {
      const itemVerdict = verdictFromMarker(bullet[1]) || verdict;
      const dish = splitDish(bullet[1]);
      if (itemVerdict && dish.name) dishes.push({ ...dish, verdict: itemVerdict });
      continue;
    }

    if (/^([-*_])\1{2,}$/.test(line)) {
      verdict = null;
      continue;
    }

    const heading =
      line.match(/^#{1,6}\s+(.*)/) ||
      line.match(/^\*{1,2}([^*]+)\*{1,2}:?$/) ||
      (line.length < 80 && (MARKER.test(line) || line.endsWith(":")) ? [line, line] : null);
    if (heading) verdict = classifySection(heading[1]);
  }

  return sortDishes(dishes);
}

function classifySection(text) {
  const t = text.toLowerCase();
  if (/🔴|❌|⛔|avoid|\bnot\b|unsuitable|unsafe|steer clear|off.?limits|\bcontains?\b|^no$/.test(t)) {
    return "avoid";
  }
  if (/🟡|🟠|⚠|ask|modif|adapt|swap|substitut|request|caution|check|confirm|might|possibl|with changes|tweak|careful/.test(t)) {
    return "ask";
  }
  if (/🟢|✅|safe|suitable|naturally|clear|good|great|recommend|options|friendly|free|enjoy|^yes$/.test(t)) {
    return "clear";
  }
  return null;
}

function verdictFromMarker(item) {
  const marker = item.match(MARKER);
  return marker ? classifySection(marker[1]) : null;
}

// "**Edamame** – steamed, salted" / "Edamame: steamed" / "Edamame (steamed)" -> name + note
function splitDish(item) {
  const text = item.replace(MARKER, "");
  const boldLead = text.match(/^\*{1,2}(.+?)\*{1,2}\s*[:–—-]?\s*(.*)$/);
  if (boldLead) return { name: cleanText(boldLead[1]), note: cleanText(boldLead[2]) };

  const plain = cleanText(text);
  const parts =
    plain.match(/^(.+?)\s+[–—-]\s+(.+)$/) ||
    plain.match(/^([^:]{2,60}):\s+(.+)$/) ||
    plain.match(/^([^(]{2,60}?)\s*\((.+)\)$/);
  return parts ? { name: parts[1].trim(), note: parts[2].trim() } : { name: plain, note: "" };
}

function cleanText(text) {
  return text.replace(/\*+/g, "").replace(/[:–—-]\s*$/, "").trim();
}

function sortDishes(dishes) {
  return dishes.sort((a, b) => VERDICTS[a.verdict].order - VERDICTS[b.verdict].order);
}

// — Results modal —

function showResult(result) {
  const { dishes, message, restaurant, location, shortPreferences } = result;
  const hasDishes = dishes.length > 0;
  const clear = dishes.filter((d) => d.verdict === "clear").length;

  resultRestaurant.textContent = restaurant;
  resultLocation.hidden = !location;
  resultLocationText.textContent = location || "";
  resultTitle.textContent = hasDishes
    ? `${clear} of ${dishes.length} ${dishes.length === 1 ? "dish looks" : "dishes look"} clear`
    : "Here's your forecast";
  resultPrefs.textContent = `Matched for ${shortPreferences.join(", ")}`;

  legend.hidden = !hasDishes;
  dishList.innerHTML = dishes.map(renderDish).join("");

  // No dishes could be picked out: show the whole reply instead (the empty state if it's blank).
  resultContent.innerHTML = hasDishes
    ? ""
    : message.trim()
      ? renderMarkdown(message)
      : "<p>No dishes came back for this menu. Try another link or a PDF of the menu.</p>";

  downloadBtn.hidden = !hasDishes && !message.trim();
  openModal(resultModal);
  closeBtn.focus();
}

function renderDish(dish) {
  const avoidGlyph =
    dish.verdict === "avoid"
      ? '<svg width="10" height="10" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" stroke-linecap="round" aria-hidden="true"><path d="M18 6 6 18"/><path d="m6 6 12 12"/></svg>'
      : "";
  return `
    <div class="dish dish-${dish.verdict}">
      <div class="dish-name">${escapeHtml(dish.name)}</div>
      <span class="tag tag-${dish.verdict}">${avoidGlyph}${VERDICTS[dish.verdict].label}</span>
      ${dish.note ? `<div class="dish-note">${escapeHtml(dish.note)}</div>` : ""}
    </div>`;
}

function closeResult() {
  closeModal(resultModal);
  submitBtn.focus();
}

