function trapFocus(event, container) {
  const focusable = [...container.querySelectorAll("button, a[href]")].filter(
    (el) => !el.hidden && el.offsetParent !== null
  );
  const first = focusable[0];
  const last = focusable[focusable.length - 1];
  if (event.shiftKey && document.activeElement === first) {
    event.preventDefault();
    last.focus();
  } else if (!event.shiftKey && document.activeElement === last) {
    event.preventDefault();
    first.focus();
  }
}

function openModal(modal) {
  modal.hidden = false;
  document.body.classList.add("modal-open");
}

function closeModal(modal) {
  modal.hidden = true;
  if (loader.hidden && resultModal.hidden) document.body.classList.remove("modal-open");
}

// — Loading modal —

function setLoading(isLoading) {
  submitBtn.disabled = isLoading;
  clearInterval(loaderTimer);

  if (!isLoading) {
    closeModal(loader);
    updateCta();
    return;
  }

  closeModal(resultModal);
  openModal(loader);
  let step = 0;
  let waiting = 0;
  showStep(0);

  // Steps 1–5 advance on a timer; once on the last step, keep rotating
  // messages until n8n answers so the modal never looks stuck.
  loaderTimer = setInterval(() => {
    if (step < LOADING_STEPS.length - 1) {
      step += 1;
      showStep(step);
    } else {
      fadeMessage(WAITING_MESSAGES[waiting % WAITING_MESSAGES.length]);
      waiting += 1;
    }
  }, LOADING_STEP_MS);
}

function showStep(step) {
  const total = LOADING_STEPS.length;
  fadeMessage(LOADING_STEPS[step]);
  // Hold just short of full until the reply actually arrives
  progressFill.style.width = `${Math.round(((step + 1) / total) * 100) - (step === total - 1 ? 5 : 0)}%`;
  progressLabel.textContent = `Step ${step + 1} of ${total}`;
}

function fadeMessage(text) {
  if (!loaderMessage.textContent) {
    loaderMessage.textContent = text;
    return;
  }
  loaderMessage.classList.add("is-fading");
  setTimeout(() => {
    loaderMessage.textContent = text;
    loaderMessage.classList.remove("is-fading");
  }, 300);
}

// Fill the bar to 100% for a moment before swapping to the results.
function finishLoading() {
  clearInterval(loaderTimer);
  progressFill.style.width = "100%";
  progressLabel.textContent = `Step ${LOADING_STEPS.length} of ${LOADING_STEPS.length}`;
  return new Promise((resolve) =>
    setTimeout(() => {
      setLoading(false);
      loaderMessage.textContent = "";
      resolve();
    }, 450)
  );
}

// — PDF download —

async function downloadPdf() {
  if (!lastResult) return;
  if (typeof html2pdf === "undefined") {
    alert("The PDF tool couldn't load. Check your internet connection and refresh the page.");
    return;
  }

  const { restaurant, location, shortPreferences, menuUrl, message, dishes } = lastResult;
  const date = new Date().toLocaleDateString(undefined, { dateStyle: "long" });
  const clear = dishes.filter((d) => d.verdict === "clear").length;

  const body = dishes.length
    ? `
      <p class="pdf-summary">${clear} of ${dishes.length} dishes look clear</p>
      <table>
        ${dishes
          .map(
            (d) => `
          <tr>
            <td>
              <div class="pdf-dish">${escapeHtml(d.name)}</div>
              ${d.note ? `<div class="pdf-note">${escapeHtml(d.note)}</div>` : ""}
            </td>
            <td><span class="tag tag-${d.verdict}">${VERDICTS[d.verdict].label}</span></td>
          </tr>`
          )
          .join("")}
      </table>`
    : renderMarkdown(message);

  const doc = document.createElement("div");
  doc.className = "pdf-doc";
  doc.innerHTML = `
    <div class="pdf-main">
      <div class="pdf-header">
        <p class="pdf-brand">Forkcast</p>
        <p class="pdf-kicker">Your Forkcast</p>
        <h1>${escapeHtml(restaurant)}</h1>
        <p class="pdf-meta">${escapeHtml(location || "Location not provided")}</p>
        ${menuUrl ? `<p class="pdf-meta">${escapeHtml(menuUrl)}</p>` : ""}
        <p class="pdf-meta">Matched for ${escapeHtml(shortPreferences.join(", "))} · ${date}</p>
      </div>
      ${body}
    </div>
    <p class="pdf-disclaimer"><strong>Disclaimer:</strong> ${DISCLAIMER}</p>
  `;

  fitToOnePage(doc);

  const slug = restaurant.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  const label = downloadBtn.querySelector("span");

  downloadBtn.disabled = true;
  label.textContent = "Preparing…";
  try {
    await html2pdf()
      .set({
        margin: PDF_MARGIN_MM,
        filename: `forkcast-${slug || "restaurant"}.pdf`,
        image: { type: "jpeg", quality: 0.95 },
        // scrollX/scrollY: 0 stops the page's scroll position from offsetting (and cropping) the capture
        html2canvas: { scale: 2, scrollX: 0, scrollY: 0 },
        jsPDF: { unit: "mm", format: "a4", orientation: "portrait" },
      })
      .from(doc)
      .save();
  } finally {
    downloadBtn.disabled = false;
    label.textContent = "Download PDF";
  }
}

// A4 is 210 x 297mm; the printable area inside the margins, in CSS pixels (96 per inch).
const PDF_MARGIN_MM = 14;
const MM_TO_PX = 96 / 25.4;
const PDF_PAGE_WIDTH_PX = Math.floor((210 - 2 * PDF_MARGIN_MM) * MM_TO_PX);
const PDF_PAGE_HEIGHT_PX = Math.floor((297 - 2 * PDF_MARGIN_MM) * MM_TO_PX) - 10; // small buffer so it never spills onto page 2

// Shrinks the text until everything fits on one A4 page, then stretches the
// layout to exactly one page tall so the disclaimer sits at the bottom.
function fitToOnePage(doc) {
  const stage = document.createElement("div");
  stage.style.cssText = `position: fixed; left: -10000px; top: 0; width: ${PDF_PAGE_WIDTH_PX}px;`;
  stage.appendChild(doc);
  document.body.appendChild(stage);

  let fontSize = 14;
  doc.style.fontSize = `${fontSize}px`;
  while (doc.scrollHeight > PDF_PAGE_HEIGHT_PX && fontSize > 7) {
    fontSize -= 0.5;
    doc.style.fontSize = `${fontSize}px`;
  }

  stage.remove();
  doc.style.height = `${PDF_PAGE_HEIGHT_PX}px`;
}

// — Text helpers —

// Minimal markdown (and WhatsApp-style *bold*): headings, bold, bullet lists, dividers and paragraphs.
function renderMarkdown(text) {
  const lines = escapeHtml(text).split("\n");
  let html = "";
  let inList = false;

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    const line = formatBold(trimmed);
    const bullet = line.match(/^[-*•]\s+(.*)/) || line.match(/^\d+\.\s+(.*)/);

    if (bullet) {
      if (!inList) {
        html += "<ul>";
        inList = true;
      }
      html += `<li>${bullet[1]}</li>`;
      continue;
    }
    if (inList) {
      html += "</ul>";
      inList = false;
    }

    // A line that is only bold text (e.g. "*🟢 Naturally Gluten-Free*") reads as a heading.
    const heading =
      trimmed.match(/^#{1,6}\s+(.*)/) || trimmed.match(/^\*{1,2}([^*]+)\*{1,2}$/);
    if (/^([-*_])\1{2,}$/.test(trimmed)) html += "<hr>";
    else if (heading) html += `<h3>${heading[1]}</h3>`;
    else if (line) html += `<p>${line}</p>`;
  }

  return inList ? html + "</ul>" : html;
}

function formatBold(line) {
  return line
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/(^|[\s(])\*(\S(?:.*?\S)?)\*(?=$|[\s).,:;!?])/g, "$1<strong>$2</strong>");
}

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

